## Cree un programa que tome tres valores por consola, multiplique el primero por el segundo y le sume el tercero

variable1 = input("Ingrese el primer valor: ")
variable2 = input("Ingrese el segundo valor: ")
variable3 = input("Ingrese el tercer valor: ")

resultado = (int(variable1) * int(variable2)) + int(variable3)

print(f"El resultado es {resultado}")